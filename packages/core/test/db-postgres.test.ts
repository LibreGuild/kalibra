import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { openSqlite, PROJECT_MIGRATIONS, type Db } from '../src/db.js';
import { PostgresPool, toPostgres, toPostgresDdl } from '../src/db-postgres.js';
import { copyDatabase } from '../src/deploy/copy.js';
import { postgresSchemas, sqliteDatabases } from '../src/deploy/databases.js';
import { Engine } from '../src/engine.js';
