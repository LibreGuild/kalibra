describe('SQL for Postgres', () => {
  it('numbers placeholders, leaving strings, quoted names and comments alone', () => {
    expect(toPostgres("SELECT '?' AS q, \"a?b\" FROM t WHERE x = ? AND y = ? -- why?\n AND z = ? /* ? */")).toBe(
      "SELECT '?' AS q, \"a?b\" FROM t WHERE x = $1 AND y = $2 -- why?\n AND z = $3 /* ? */",
    );
    expect(toPostgres("SELECT 'it''s ?' WHERE a = ?")).toBe("SELECT 'it''s ?' WHERE a = $1");
  });

  it("ignores ASCII case in LIKE (as SQLite does) and in lower(?)", () => {
    expect(toPostgres("SELECT 1 FROM t WHERE a LIKE ? ESCAPE '\\' OR b NOT LIKE ?")).toBe("SELECT 1 FROM t WHERE a ILIKE $1 ESCAPE '\\' OR b NOT ILIKE $2");
    expect(toPostgres('SELECT 1 FROM users WHERE lower(username) = lower(?)')).toBe('SELECT 1 FROM users WHERE lower(username) = lower(CAST($1 AS TEXT) COLLATE "C")');
  });

  it('refuses SQLite-only SQL loudly instead of guessing', () => {
    for (const sql of [
      'INSERT OR IGNORE INTO t (a) VALUES (?)',
      "SELECT json_extract(x, '$.a') FROM t",
      'SELECT rowid FROM t',
      'PRAGMA user_version',
      'SELECT 1 FROM t WHERE a = ? COLLATE NOCASE',
      'SELECT 1 FROM t WHERE a IS ?',
      'SELECT IFNULL(a, 1) FROM t',
    ]) {
      expect(() => toPostgres(sql), sql).toThrow(/not portable to Postgres/);
    }
    expect(() => toPostgres("SELECT 'json_extract(' FROM t")).not.toThrow(); // only in code, not in strings
  });

  it('turns SQLite DDL into Postgres DDL', () => {
    const ddl = toPostgresDdl(`
      -- INTEGER and TEXT in a comment stay as they are
      CREATE TABLE a (id INTEGER PRIMARY KEY AUTOINCREMENT, n INTEGER NOT NULL, r REAL, b BLOB, name TEXT NOT NULL COLLATE NOCASE, note TEXT DEFAULT 'TEXT');
      CREATE INDEX a_name ON a(name COLLATE NOCASE);
      ALTER TABLE a ADD COLUMN extra TEXT;`);
    expect(ddl).toContain('-- INTEGER and TEXT in a comment stay as they are');
    expect(ddl).toContain('id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
    expect(ddl).toContain('n BIGINT NOT NULL');
    expect(ddl).toContain('r DOUBLE PRECISION, b BYTEA');
    expect(ddl).toContain('name TEXT COLLATE "C" NOT NULL,');
    expect(ddl).toContain("note TEXT COLLATE \"C\" DEFAULT 'TEXT'");
    expect(ddl).toContain('ON a(name);');
    expect(ddl).toContain('ADD COLUMN extra TEXT COLLATE "C";');
  });
});

/*
 * Against a real Postgres: the one in KALIBRA_TEST_DATABASE_URL (CI), else PGlite (Postgres compiled
 * to WebAssembly, in process) for everything that needs only one connection at a time.
 */
describe('the Postgres driver', () => {
  let pool: PostgresPool;
  let stop: (() => Promise<void>) | undefined;
  const prefix = `pgt${Date.now().toString(36)}`;
  const dirs: string[] = [];
  const tmp = () => {
    const d = mkdtempSync(join(tmpdir(), 'kalibra-pg-'));
    dirs.push(d);
    return d;
  };
  let schemaN = 0;
  const open = (migrations = PROJECT_MIGRATIONS) => pool.open(`${prefix}_s${++schemaN}`, migrations);

  beforeAll(async () => {
    if (testDatabaseUrl) {
      pool = await PostgresPool.connect({ url: testDatabaseUrl, max: 4 });
      return;
    }
    const { PGlite } = await import('@electric-sql/pglite');
    const { PGLiteSocketServer } = await import('@electric-sql/pglite-socket');
    const db = await PGlite.create();
    const port = 40000 + Math.floor(Math.random() * 20000);
    const server = new PGLiteSocketServer({ db, port, host: '127.0.0.1' });
    await server.start();
    pool = await PostgresPool.connect({ url: `postgres://postgres@127.0.0.1:${port}/postgres`, max: 1 });
    stop = async () => {
      await server.stop();
      await db.close();
    };
  }, 60_000);

  afterAll(async () => {
    for (const s of (await pool?.schemas(`${prefix}_`)) ?? []) await pool.dropSchema(s);
    await pool?.close();
    await stop?.();
    dirs.forEach((d) => rmSync(d, { recursive: true, force: true }));
  });

  it('creates the same tables, columns, keys and indexes as SQLite', async () => {
    for (const migrations of [PROJECT_MIGRATIONS, HUB_MIGRATIONS]) {
      const lite = await openSqlite(join(tmp(), 'x.db'), migrations);
      const pg = await open(migrations);
      const shape = async (db: Db) => (await db.tables()).map((t) => ({ ...t, columns: [...t.columns].sort(), references: [...t.references].sort(), identity: [] })).sort((a, b) => a.name.localeCompare(b.name));
      expect(await shape(pg)).toEqual(await shape(lite));
      const liteIdx = (await lite.all("SELECT name FROM sqlite_master WHERE type = 'index' AND name NOT LIKE 'sqlite_%' ORDER BY name")).map((r) => r.name);
      const pgIdx = (await pg.all("SELECT indexname AS name FROM pg_indexes WHERE schemaname = current_schema() AND indexname NOT LIKE '%_pkey' AND indexname NOT LIKE '%_key' ORDER BY indexname")).map((r) => r.name);
      expect(pgIdx).toEqual(liteIdx);
      await lite.close();
    }
  });

  it('migrates once, and refuses data from a newer version', async () => {
    const name = `${prefix}_mig`;
    await pool.open(name, PROJECT_MIGRATIONS);
    await pool.open(name, PROJECT_MIGRATIONS); // again: nothing to do
    await expect(pool.open(name, PROJECT_MIGRATIONS.slice(0, 2))).rejects.toThrow(/newer version of Kalibra/);
  });

  it('returns values the way SQLite does', async () => {
    const db = await open();
    await db.run("INSERT INTO meta (key, value) VALUES ('a', '1'), ('b', '2')");
    expect(await db.get('SELECT COUNT(*) AS n, SUM(length(value)) AS s, AVG(1.5) AS a, 1 = 1 AS t, 1 = 2 AS f FROM meta')).toEqual({ n: 2, s: 2, a: 1.5, t: 1, f: 0 });
    expect(await db.get('SELECT ? AS x', 'it?s')).toEqual({ x: 'it?s' });
    expect((await db.run('UPDATE meta SET value = ? WHERE key IN (?, ?)', 'z', 'a', 'b')).changes).toBe(2);
    await expect(db.get('SELECT 9007199254740993::bigint AS big')).rejects.toThrow(/too large/);
    await expect(db.run('INSERT INTO meta (key, value) VALUES (?, ?)', 'c', { an: 'object' })).rejects.toThrow(/Cannot bind/);
  });

  it('commits, rolls back on errors, and joins nested transactions', async () => {
    const db = await open();
    await db.tx(async () => {
      await db.run("INSERT INTO meta (key, value) VALUES ('t1', 'x')");
      await db.tx(async () => db.run("INSERT INTO meta (key, value) VALUES ('t2', 'x')"));
    });
    await expect(
      db.tx(async () => {
        await db.run("INSERT INTO meta (key, value) VALUES ('t3', 'x')");
        throw new Error('nope');
      }),
    ).rejects.toThrow('nope');
    expect((await db.all("SELECT key FROM meta WHERE key LIKE 'T%' ORDER BY key")).map((r) => r.key)).toEqual(['t1', 't2']);
  });

  it.skipIf(!testDatabaseUrl)('retries a transaction that collides with another one (serializable)', async () => {
    const db = await open();
    await db.run("INSERT INTO meta (key, value) VALUES ('counter', '0')");
    // Many read-modify-write transactions at once: none may lose an update, none may fail.
    const bump = () =>
      db.tx(async () => {
        const n = Number((await db.get("SELECT value FROM meta WHERE key = 'counter'")).value);
        await new Promise((r) => setTimeout(r, 2));
        await db.run("UPDATE meta SET value = ? WHERE key = 'counter'", String(n + 1));
      });
    await Promise.all(Array.from({ length: 12 }, bump));
    expect((await db.get("SELECT value FROM meta WHERE key = 'counter'")).value).toBe('12');
  });

  it('refuses work once closed, like a closed SQLite file', async () => {
    const db = await open();
    await db.close();
    await expect(db.get('SELECT 1 AS x')).rejects.toThrow(/not open/);
  });

  it('copies a project to Postgres and back without losing anything', async () => {
    const dir = tmp();
    const engine = await Engine.open({ dir, db: await sqliteDatabases().project(undefined, dir) });
    await engine.call('create_dataset', { name: 'Questions', columns: [{ key: 'q' }, { key: 'expected' }] });
    await engine.call('add_dataset_rows', { dataset: 'Questions', rows: [{ data: { q: 'Ünïcödé ✓', expected: 'a' }, tags: ['x'] }, { data: { q: "it's", expected: 'b' } }] });
    await engine.call('upload_file', { name: 'a.txt', base64: Buffer.from('hello').toString('base64') });
    const source = engine.db;
    const pg = await open();
    const there = await copyDatabase(source, pg);
    expect(there.rows).toBeGreaterThan(5);
    const back = await openSqlite(join(tmp(), 'back.db'));
    await copyDatabase(pg, back);
    for (const t of await source.tables()) {
      const key = t.primaryKey.join(', ');
      expect(await back.all(`SELECT * FROM ${t.name} ORDER BY ${key}`), t.name).toEqual(await source.all(`SELECT * FROM ${t.name} ORDER BY ${key}`));
    }
    // Ids written by the database itself continue after the copied ones.
    const before = (await pg.get('SELECT MAX(id) AS id FROM activity')).id;
    await pg.run("INSERT INTO activity (at, actor, op) VALUES ('2026-01-01', '{}', 'x')");
    expect((await pg.get('SELECT MAX(id) AS id FROM activity')).id).toBe(before + 1);
    await expect(copyDatabase(source, pg)).rejects.toThrow(/already has data/);
    await engine.close();
    await back.close();
  });

  it('keeps each deployment in its own schemas', async () => {
    const a = postgresSchemas(pool, `${prefix}_a`);
    const b = postgresSchemas(pool, `${prefix}_b`);
    const dir = tmp();
    expect(await a.exists('hub', undefined, dir)).toBe(false);
    const hubA = await a.hub(dir);
    await hubA.run("INSERT INTO settings (key, value) VALUES ('who', 'a')");
    expect(await a.exists('hub', undefined, dir)).toBe(true);
    expect(await (await b.hub(dir)).get("SELECT value FROM settings WHERE key = 'who'")).toBeUndefined();
    expect(await a.exists('project', 'prj_1', dir)).toBe(false);
  });
});
